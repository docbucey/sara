class ControlIngestBufferGuard:
    """
    Tracks ingest preview buffers so control keeps RAM usage bounded.
    Default policy keeps total in-process preview buffers under 3% of system RAM.
    """
    def __init__(self, max_percent: float = 3.0):
        self.max_percent = max(0.1, float(max_percent))
        total_ram = self._total_ram_bytes()
        self.max_bytes = int(total_ram * (self.max_percent / 100.0))
        self._in_use_bytes = 0
        self._lock = threading.Lock()

    def _total_ram_bytes(self) -> int:
        if psutil is not None:
            try:
                return int(psutil.virtual_memory().total)
            except Exception:
                pass
        # Safe fallback when psutil is unavailable.
        return 8 * 1024 * 1024 * 1024


def _process_memory_percent_con() -> Optional[float]:
    if psutil is None:
        return None
    try:
        rss = psutil.Process(os.getpid()).memory_info().rss
        total = psutil.virtual_memory().total
        if total <= 0:
            return None
        return (rss / total) * 100.0
    except Exception:
        return None


def _process_cpu_percent_con() -> Optional[float]:
    if psutil is None:
        return None
    try:
        proc = psutil.Process(os.getpid())
        proc.cpu_percent(interval=None)
        cpu_count = max(1, int(psutil.cpu_count() or 1))
        return proc.cpu_percent(interval=0.02) / float(cpu_count)
    except Exception:
        return None


def _user_interactive_active_con(idle_threshold_sec: int = 90) -> Optional[bool]:
    """
    Return True when recent local user input is detected.
    Windows-only best effort; returns None when unavailable.
    """
    try:
        if os.name != "nt":
            return None
        import ctypes
        from ctypes import wintypes

        class LASTINPUTINFO(ctypes.Structure):
            _fields_ = [("cbSize", wintypes.UINT), ("dwTime", wintypes.DWORD)]

        info = LASTINPUTINFO()
        info.cbSize = ctypes.sizeof(LASTINPUTINFO)
        if not ctypes.windll.user32.GetLastInputInfo(ctypes.byref(info)):
            return None
        tick_now = ctypes.windll.kernel32.GetTickCount()
        idle_ms = max(0, int(tick_now - info.dwTime))
        return idle_ms < (max(5, int(idle_threshold_sec)) * 1000)
    except Exception:
        return None


class ControlSystemStrainBudget:
    """Adaptive ingest budget that favors stable desktop behavior over burst speed."""

    def __init__(self, max_percent: float = 3.0):
        self.max_percent = max(0.1, float(max_percent))

    def snapshot(
        self,
        buffer_guard: Optional[ControlIngestBufferGuard] = None,
        interactive_user_active: Optional[bool] = None,
    ) -> Dict[str, Any]:
        process_mem_pct = _process_memory_percent_con()
        process_cpu_pct = _process_cpu_percent_con()
        guard_usage = buffer_guard.usage() if buffer_guard is not None else {}
        mode = self._mode_for(
            process_mem_pct=process_mem_pct,
            process_cpu_pct=process_cpu_pct,
            guard_usage_percent=guard_usage.get("guard_usage_percent"),
            interactive_user_active=interactive_user_active,
        )
        return {
            "max_percent": self.max_percent,
            "process_memory_percent": process_mem_pct,
            "process_cpu_percent": process_cpu_pct,
            "interactive_user_active": interactive_user_active,
            "mode": mode,
            **guard_usage,
        }

    def _mode_for(
        self,
        process_mem_pct: Optional[float],
        process_cpu_pct: Optional[float],
        guard_usage_percent: Optional[float],
        interactive_user_active: Optional[bool],
    ) -> str:
        if (
            (process_mem_pct is not None and process_mem_pct >= self.max_percent)
            or (guard_usage_percent is not None and guard_usage_percent >= 90.0)
            or (process_cpu_pct is not None and process_cpu_pct >= 85.0)
        ):
            return "critical"
        if (
            (process_mem_pct is not None and process_mem_pct >= (self.max_percent * 0.75))
            or (guard_usage_percent is not None and guard_usage_percent >= 75.0)
            or (process_cpu_pct is not None and process_cpu_pct >= 65.0)
        ):
            return "constrained"
        if (
            (process_mem_pct is not None and process_mem_pct >= (self.max_percent * 0.5))
            or (guard_usage_percent is not None and guard_usage_percent >= 50.0)
            or (process_cpu_pct is not None and process_cpu_pct >= 40.0)
        ):
            return "pressure"
        if interactive_user_active is True:
            return "pressure"
        return "normal"

    def recommended_worker_count(
        self,
        base_worker_count: int,
        buffer_guard: Optional[ControlIngestBufferGuard] = None,
        interactive_user_active: Optional[bool] = None,
    ) -> Dict[str, Any]:
        base_worker_count = max(1, int(base_worker_count))
        snapshot = self.snapshot(buffer_guard, interactive_user_active=interactive_user_active)
        mode = snapshot["mode"]
        if mode == "critical":
            worker_count = 1
        elif mode == "constrained":
            worker_count = min(base_worker_count, 2)
        elif mode == "pressure":
            worker_count = max(1, min(base_worker_count, max(1, base_worker_count // 2)))
        else:
            worker_count = base_worker_count
        return {
            "worker_count": worker_count,
            "mode": mode,
            "snapshot": snapshot,
        }

    def preview_plan(
        self,
        preview_bytes: int,
        ext_l: str,
        buffer_guard: Optional[ControlIngestBufferGuard] = None,
        interactive_user_active: Optional[bool] = None,
    ) -> Dict[str, Any]:
        snapshot = self.snapshot(buffer_guard, interactive_user_active=interactive_user_active)
        mode = snapshot["mode"]
        preview_bytes = max(256, int(preview_bytes))
        heavy_preview_exts = {
            ".docx", ".pdf", ".xlsx",
            ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tiff", ".webp",
            ".mp4", ".mov", ".avi", ".mkv", ".webm",
            ".mp3", ".wav", ".flac", ".ogg", ".m4a", ".aac",
            ".stl", ".obj",
        }
        if interactive_user_active is True and ext_l in heavy_preview_exts:
            return {
                "mode": "interactive",
                "allow_preview": False,
                "preview_bytes": 0,
                "parser_status": "interactive_metadata_only",
                "offload": False,
                "snapshot": snapshot,
            }
        if mode == "critical":
            return {
                "mode": mode,
                "allow_preview": False,
                "preview_bytes": 0,
                "parser_status": "system_strain_critical",
                "offload": False,
                "snapshot": snapshot,
            }
        if mode == "constrained" and ext_l in heavy_preview_exts:
            return {
                "mode": mode,
                "allow_preview": False,
                "preview_bytes": 0,
                "parser_status": "strain_metadata_only",
                "offload": False,
                "snapshot": snapshot,
            }
        if mode == "constrained":
            preview_bytes = max(256, preview_bytes // 4)
        elif mode == "pressure":
            preview_bytes = max(256, preview_bytes // 2)
        return {
            "mode": mode,
            "allow_preview": True,
            "preview_bytes": preview_bytes,
            "parser_status": "metadata_only",
            "offload": ext_l in heavy_preview_exts,
            "snapshot": snapshot,
        }


def _preview_worker_creationflags_con() -> int:
    flags = 0
    flags |= getattr(subprocess, "CREATE_NO_WINDOW", 0)
    flags |= getattr(subprocess, "IDLE_PRIORITY_CLASS", 0)
    return flags


def _run_preview_worker_con(local_path: str, ext_l: str, max_chars: int, timeout_sec: int = 20) -> Dict[str, Any]:
    worker_code = """
import json
import re
import sys
import zipfile
import importlib

path = sys.argv[1]
ext_l = sys.argv[2].lower()
max_chars = max(256, int(sys.argv[3]))
result = {"preview": None, "image_meta": {}, "parser_status": "metadata_only"}

try:
    if ext_l == ".docx":
        with zipfile.ZipFile(path, "r") as zf:
            raw = zf.read("word/document.xml")
        text = raw.decode("utf-8", errors="ignore")
        text = re.sub(r"<[^>]+>", " ", text)
        text = " ".join(text.split())
        result["preview"] = text[:max_chars] or None
        result["parser_status"] = "preview_docx_offloaded" if result["preview"] else "docx_no_preview"
    elif ext_l == ".pdf":
        pypdf2 = importlib.import_module("PyPDF2")
        with open(path, "rb") as f:
            reader = pypdf2.PdfReader(f)
            if reader.pages:
                text = reader.pages[0].extract_text() or ""
                result["preview"] = text[:max_chars] or None
        result["parser_status"] = "preview_pdf_offloaded" if result["preview"] else "pdf_no_preview"
    elif ext_l == ".xlsx":
        openpyxl = importlib.import_module("openpyxl")
        wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
        sheet = wb.worksheets[0] if wb.worksheets else None
        rows = []
        if sheet is not None:
            for ridx, row in enumerate(sheet.iter_rows(values_only=True), start=1):
                if ridx > 20:
                    break
                vals = [str(c) for c in row if c is not None]
                if vals:
                    rows.append(", ".join(vals))
        wb.close()
        text = "\\n".join(rows)
        result["preview"] = text[:max_chars] or None
        result["parser_status"] = "preview_xlsx_offloaded" if result["preview"] else "xlsx_no_preview"
    elif ext_l in {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tiff", ".webp"}:
        pil_image = importlib.import_module("PIL.Image")
        with pil_image.open(path) as im:
            result["image_meta"] = {
                "format": im.format,
                "mode": im.mode,
                "width": im.width,
                "height": im.height,
            }
        result["parser_status"] = "image_metadata_offloaded"
    elif ext_l in {".mp4", ".mov", ".avi", ".mkv", ".webm", ".mp3", ".wav", ".flac", ".ogg", ".m4a", ".aac", ".stl", ".obj"}:
        import os
        result["media_meta"] = {
            "ext": ext_l,
            "size_bytes": os.path.getsize(path),
        }
        result["parser_status"] = "media_metadata_offloaded"
except Exception:
    result["parser_status"] = "preview_worker_failed"

print(json.dumps(result))
"""
    try:
        proc = subprocess.run(
            [sys.executable, "-c", worker_code, local_path, ext_l, str(max_chars)],
            cwd=os.path.dirname(local_path) or None,
            capture_output=True,
            text=True,
            check=False,
            timeout=max(5, int(timeout_sec)),
            creationflags=_preview_worker_creationflags_con(),
        )
    except Exception:
        return {"preview": None, "image_meta": {}, "parser_status": "preview_worker_failed"}

    if proc.returncode != 0 or not proc.stdout.strip():
        return {"preview": None, "image_meta": {}, "parser_status": "preview_worker_failed"}

    try:
        result = json.loads(proc.stdout.strip())
    except Exception:
        return {"preview": None, "image_meta": {}, "parser_status": "preview_worker_failed"}

    if not isinstance(result, dict):
        return {"preview": None, "image_meta": {}, "parser_status": "preview_worker_failed"}
    return result

def ingest_artifacts_con(con_project: str = SYSTEM_CORE_PROJECT_NAME,
                         con_sources: Optional[List[str]] = None,
                         con_narrative_path: Optional[str] = None,
                         con_tags: Optional[List[str]] = None,
                         con_preview_bytes: int = 2048,
                         con_max_buffer_percent: float = 3.0,
                         con_distributed_workers: Optional[int] = None,
                         con_interactive_guard: bool = True,
                         con_user_idle_seconds: int = 90,
                         con_security_token: str = "",
                         con_envoy_mode: bool = False,
                         con_use_windows_defender: bool = True) -> Dict[str, Any]:
    """
    Create NBS artifact_wrapper files for artifacts found in source folders.
    Supports markdown, logs, text, Python code, JSON/NBS, and zip archives.

    Writes individual artifact wrapper NBS files under: nbs_projects/<project>/artifacts/
    Appends a summary event to the provided narrative (or starts a new session).
    """
    con_sources = con_sources or []
    for i, p in enumerate(con_sources):
        if isinstance(p, str):
            con_sources[i] = os.path.abspath(p)

    # Ensure we have a narrative to write to
    if not con_narrative_path:
        con_start = start_session_con(con_project, con_session_note="Artifact ingestion session start")
        if not con_start.get("success"):
            return con_start
        con_narrative_path = con_start["reference"]["file_path"]

    # Extensions to include
    include_exts = {
        ".json", ".nbs", ".md", ".markdown", ".log", ".txt", ".py", ".zip",
        ".csv", ".pdf", ".docx", ".xls", ".xlsx",
        ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tiff", ".webp",
        ".mp4", ".mov", ".avi", ".mkv", ".webm",
        ".mp3", ".wav", ".flac", ".ogg", ".m4a", ".aac",
        ".stl", ".obj",
    }
    text_like_exts = {".md", ".markdown", ".log", ".txt", ".py", ".json", ".nbs", ".csv"}
    artifacts_created: List[Dict[str, Any]] = []
    artifacts_skipped: List[Dict[str, Any]] = []
    parser_status_counts: Dict[str, int] = {}
    strain_mode_counts: Dict[str, int] = {}

    con_art_dir = os.path.join(NBS_BASE_DIR, con_project, "artifacts")
    os.makedirs(con_art_dir, exist_ok=True)
    con_clean_dir = os.path.join(NBS_BASE_DIR, con_project, "ingest_clean")
    os.makedirs(con_clean_dir, exist_ok=True)

    buffer_guard = ControlIngestBufferGuard(max_percent=con_max_buffer_percent)
    strain_budget = ControlSystemStrainBudget(max_percent=con_max_buffer_percent)
    interactive_user_active = (
        _user_interactive_active_con(con_user_idle_seconds) if con_interactive_guard else False
    )

    def _sanitize_name_con(s: str) -> str:
        return "".join(ch if ch.isalnum() or ch in ("_", "-") else "_" for ch in s)[:80]

    candidates: List[Dict[str, Any]] = []
    for src in con_sources:
        if not src or not os.path.exists(src):
            continue
        for root, dirs, files in os.walk(src):
            for fname in files:
                _, ext = os.path.splitext(fname)
                ext_l = ext.lower()
                if ext_l not in include_exts:
                    continue
                candidates.append(
                    {
                        "src_path": os.path.join(root, fname),
                        "fname": fname,
                        "ext": ext_l,
                    }
                )

    def _process_candidate(item: Dict[str, Any]) -> Dict[str, Any]:
        fpath = item["src_path"]
        fname = item["fname"]
        ext_l = item["ext"]
        try:
            fsize = os.path.getsize(fpath)
        except Exception:
            return {"success": False, "artifact_path": fpath, "error": "size-read-failed"}

        hash_input = f"{fpath}:{fsize}:{os.path.getmtime(fpath)}".encode("utf-8", errors="ignore")
        h = hashlib.sha256(hash_input).hexdigest()[:24]
        clean_name = f"clean_{h}_{_sanitize_name_con(fname)}"
        clean_path = os.path.join(con_clean_dir, clean_name)
        try:
            if not os.path.exists(clean_path):
                shutil.copy2(fpath, clean_path)
        except Exception as e:
            return {"success": False, "artifact_path": fpath, "error": f"clean-copy-failed:{e}"}

        sec_command = "scan_envoy" if con_envoy_mode else "scan_file"
        sec = dispatch_security(
            sec_command,
            auth_token=con_security_token,
            file_path=clean_path,
            file_ext=ext_l,
            max_file_bytes=100 * 1024 * 1024,
            use_windows_defender=con_use_windows_defender,
        )
        sec_ok = bool(sec.get("success"))
        sec_result = sec.get("result", {}) if isinstance(sec, dict) else {}
        if not sec_ok or not sec_result.get("allowed", False):
            return {
                "success": False,
                "artifact_path": fpath,
                "clean_path": clean_path,
                "error": sec_result.get("reason", "SEC:DENY:scan-failed"),
                "security": sec,
            }

        preview_plan = strain_budget.preview_plan(
            preview_bytes=con_preview_bytes,
            ext_l=ext_l,
            buffer_guard=buffer_guard,
            interactive_user_active=interactive_user_active,
        )
        preview_char_cap = int(max(256, preview_plan["preview_bytes"])) if preview_plan["preview_bytes"] else 0
        preview_str: Optional[str] = None
        preview_bytes_reserved = int(
            min(max(256, max(preview_char_cap, 256)), max(1024, buffer_guard.max_bytes // 10))
        )
        parser_status = str(preview_plan["parser_status"])
        image_meta: Dict[str, Any] = {}
        strain_snapshot = preview_plan["snapshot"]

        if preview_plan["allow_preview"]:
            if buffer_guard.try_acquire(preview_bytes_reserved):
                try:
                    if ext_l in text_like_exts:
                        with open(clean_path, "r", encoding="utf-8", errors="ignore") as f:
                            preview_str = f.read(preview_char_cap)
                        parser_status = "preview_text"
                    elif preview_plan["offload"]:
                        worker_result = _run_preview_worker_con(clean_path, ext_l, preview_char_cap)
                        preview_str = worker_result.get("preview")
                        image_meta = worker_result.get("image_meta", {}) or {}
                        parser_status = str(worker_result.get("parser_status", "preview_worker_failed"))
                    elif ext_l == ".xls":
                        parser_status = "xls_metadata_only"
                finally:
                    buffer_guard.release(preview_bytes_reserved)
            else:
                parser_status = "buffer_guard_limit"

        con_content = {
            "artifact_type": "file",
            "path": fpath,
            "clean_path": clean_path,
            "ext": ext_l,
            "size": fsize,
            "preview": preview_str,
            "parser_status": parser_status,
            "memory_guard": {
                **buffer_guard.usage(),
                **strain_snapshot,
            },
            "image_meta": image_meta,
            "security_scan": sec_result,
            "tags": array_normalize_con(con_tags or ["artifact", ext_l.strip(".")]),
        }

        rel_name = (
            f"artifact_{int(datetime.now(timezone.utc).timestamp() * 1000)}_"
            f"{h}_{_sanitize_name_con(fname)}_gen0_1.0_nbs.json"
        )
        rel_path = os.path.join("artifacts", rel_name)

        write_res = create_nbs_file(
            project_name=con_project,
            relative_path=rel_path,
            content=con_content,
            meta={
                "nbs_type": "artifact_wrapper",
                "tags": ["artifact", ext_l.strip(".")],
                "source": "control",
                "project_name": con_project,
            },
        )
        if not write_res.get("success"):
            return {"success": False, "artifact_path": fpath, "error": "wrapper-write-failed"}

        return {
            "success": True,
            "artifact_path": fpath,
            "clean_path": clean_path,
            "wrapper_path": write_res["reference"]["file_path"],
            "ext": ext_l,
            "size": fsize,
            "parser_status": parser_status,
            "strain_mode": preview_plan["mode"],
        }

    base_worker_count = con_distributed_workers
    if base_worker_count is None:
        base_worker_count = min(4, max(1, (os.cpu_count() or 2)))
    worker_plan = strain_budget.recommended_worker_count(
        base_worker_count,
        buffer_guard,
        interactive_user_active=interactive_user_active,
    )
    worker_count = int(worker_plan["worker_count"])

    if candidates:
        with ThreadPoolExecutor(max_workers=worker_count) as executor:
            futures = [executor.submit(_process_candidate, item) for item in candidates]
            for fut in as_completed(futures):
                result = fut.result()
                ps = str(result.get("parser_status", "unknown"))
                parser_status_counts[ps] = parser_status_counts.get(ps, 0) + 1
                sm = str(result.get("strain_mode", worker_plan["mode"]))
                strain_mode_counts[sm] = strain_mode_counts.get(sm, 0) + 1
                if result.get("success"):
                    artifacts_created.append(result)
                else:
                    artifacts_skipped.append(result)

    con_event = {
        "event_type": "ingest_artifacts",
        "sources": array_normalize_con(con_sources),
        "distributed_workers": worker_count,
        "requested_workers": base_worker_count,
        "max_buffer_percent": con_max_buffer_percent,
        "interactive_guard": con_interactive_guard,
        "interactive_user_active": interactive_user_active,
        "user_idle_seconds_threshold": con_user_idle_seconds,
        "strain_mode": worker_plan["mode"],
        "strain_mode_counts": strain_mode_counts,
        "strain_snapshot": worker_plan["snapshot"],
        "parser_status_counts": parser_status_counts,
        "envoy_mode": con_envoy_mode,
        "scanned": len(candidates),
        "count": len(artifacts_created),
        "skipped": len(artifacts_skipped),
        "artifacts": artifacts_created[:50],
        "skipped_artifacts": artifacts_skipped[:50],
        "note": "Created artifact_wrapper NBS files using adaptive distributed ingest, disk-first clean cache, and offloaded heavy previews",
    }
    con_app = append_event_con(con_project, con_narrative_path, con_event)
    if not con_app.get("success"):
        return con_app

    return {
        "success": True,
        "narrative_path": con_narrative_path,
        "count": len(artifacts_created),
        "skipped": len(artifacts_skipped),
        "distributed_workers": worker_count,
        "requested_workers": base_worker_count,
        "strain_mode": worker_plan["mode"],
        "strain_mode_counts": strain_mode_counts,
        "parser_status_counts": parser_status_counts,
        "max_buffer_percent": con_max_buffer_percent,
        "interactive_guard": con_interactive_guard,
        "interactive_user_active": interactive_user_active,
        "envoy_mode": con_envoy_mode,
    }


