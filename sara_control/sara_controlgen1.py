def job_intake_filter(job_payload: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Deterministically filter WFH gig jobs for remote, deliverable-based, BOSGAME-compatible work."""
    payload = dict(job_payload or {})
