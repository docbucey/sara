# --- CONTROL Server Loop ---
def control_server():
    print("SARA ready in stand by")
    try:
        while True:
            user_input = input("[CONTROL] > ").strip().lower()
            if user_input == "goodbye":
                print("SARA CONTROL shutting down. Goodbye!")
                break
            elif user_input:
                print(f"[CONTROL] Received: {user_input} (no-op in stand by mode)")
    except (KeyboardInterrupt, EOFError):
        print("\nSARA CONTROL interrupted. Goodbye!")

if __name__ == "__main__":
    control_server()